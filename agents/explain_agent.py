"""Explanation node used by the EXPLAIN intent (LLM-backed, with a factual static fallback)."""
from __future__ import annotations

from agents.llm import get_provider, run_structured
from agents.state import ExplainOut, ReviewState, numbered, traced
from rag.retriever import format_context

SYSTEM = (
    "You are a senior engineer explaining code to a colleague. Explain what the code does, how it works step by step, its time/space "
    "complexity, and any notable pitfalls. Be accurate; do not speculate about code that is not shown. "
    'Return JSON: {{"explanation": str, "complexity": str, "key_points": [str]}}.'
)
HUMAN = ("User's question (untrusted): {request}\n\n<reference_docs>\n{context}\n</reference_docs>\n\n"
         "<untrusted_code>\n{code}\n</untrusted_code>\n{extra}")


@traced("explain", "Code explanation")
def run(state: ReviewState) -> dict:
    if state.get("analysis_mode") == "llm":
        out = run_structured(
            get_provider(), SYSTEM, HUMAN,
            {"request": (state.get("request") or "Explain this code.")[:1500],
             "context": format_context(state.get("context", [])), "code": numbered(state["code"])},
            ExplainOut,
        )
        return {"explanation": {"source": "llm", **out.model_dump()}, "_summary": "Explanation generated by the LLM."}
    if state.get("analysis_mode") == "demo_simulated":
        from agents import demo_data

        s = demo_data.match_sample(state.get("sample_id"), state["code"])
        return {"explanation": {"source": "demo_simulated", "explanation": s.get("explanation") or "Predefined demo explanation.",
                                "complexity": "", "key_points": []}, "_summary": "Simulated demo explanation."}
    m = state.get("static_metrics", {})
    funcs = m.get("functions", [])
    lines = [f"`{f['name']}` (line {f['line']}, {f['length']} lines, cyclomatic complexity {f['complexity']})" for f in funcs]
    text = (f"No LLM is configured, so no natural-language explanation could be generated. Static structure: "
            f"{m.get('loc', 0)} non-blank lines, {len(funcs)} function(s), {m.get('classes', 0)} class(es).")
    return {"explanation": {"source": "static", "explanation": text, "complexity": "", "key_points": lines},
            "_status": "degraded", "notes": ["Explanation unavailable without an LLM; showing static structure only."],
            "_summary": "LLM unavailable: structural summary only."}
